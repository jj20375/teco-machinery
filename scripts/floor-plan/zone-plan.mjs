//
// `pick.base` / `pick.zones` 分開設定，是因為兩層的紅框檔匯出管道不同：
// - B1 紅框檔是 Illustrator 匯出，紅框和底圖混在同一層，只能靠 class 篩（`kind: 'class'`）
// - B2 紅框檔是 PDF 轉出，設計端已把紅框放進獨立的 <g>（`kind: 'group'`）
//
// 要調整分區就回去改紅框檔再重跑 `npm run extract:floor-plan`。

